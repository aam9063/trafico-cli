package cli

// The command reference is GENERATED from the live cobra tree, never written
// by hand (AGENT-02). A reference a human maintains is wrong within a month:
// docs/ARRANQUE.md §6.2 cited `trafico schema incidents` long after the
// command had stopped existing under that name. Rendering from the tree makes
// that class of drift impossible, and TestCLISpecIsCurrent fails when the
// committed file stops matching what the binary would print.

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// exitCodeReference is copied from docs/ARRANQUE.md §6.3. It is a constant of
// the contract, not something the tree can carry, so it is stated here next to
// the text that publishes it.
var exitCodeReference = [][2]string{
	{"0", "éxito: la respuesta va en stdout"},
	{"2", "error de uso: argumento o flag inválido"},
	{"3", "error de configuración o de almacenamiento"},
	{"4", "no encontrado: la ruta, el lugar o la vigilancia no existen"},
	{"5", "error de red o el feed no está disponible"},
	{"6", "error interno"},
	{"7", "el feed ha cambiado: la DGT publica algo que no sabemos leer"},
}

// RenderCLISpec renders the whole command tree as markdown. Order is stable
// (commands and flags sorted) so the generated file only changes when the CLI
// does.
func RenderCLISpec(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("# trafico-cli · command reference\n\n")
	b.WriteString("<!-- Generated by `RenderCLISpec` from the live cobra tree. Do not edit by hand:\n")
	b.WriteString("     run `go test ./internal/cli -run TestCLISpecIsCurrent -update` to regenerate. -->\n\n")
	b.WriteString("Every command prints human-readable Spanish text by default; `--json` prints the single\n")
	b.WriteString("JSON value documented in `schemas/`, which is what an agent parses. Diagnostics go to\n")
	b.WriteString("stderr only. Every response carries `attribution` and `meta`.\n\n")

	b.WriteString("## Exit codes\n\n")
	b.WriteString("| Code | Meaning |\n|---|---|\n")
	for _, row := range exitCodeReference {
		fmt.Fprintf(&b, "| `%s` | %s |\n", row[0], row[1])
	}
	b.WriteString("\n## Commands\n\n")

	var walk func(cmd *cobra.Command, path string)
	walk = func(cmd *cobra.Command, path string) {
		if cmd.Hidden || cmd.Deprecated != "" {
			return
		}
		if path != "" {
			fmt.Fprintf(&b, "### `%s`\n\n", path)
			if long := strings.TrimSpace(cmd.Long); long != "" {
				b.WriteString(long + "\n\n")
			} else if short := strings.TrimSpace(cmd.Short); short != "" {
				b.WriteString(short + "\n\n")
			}
			if use := cmd.Use; strings.Contains(use, " ") {
				fmt.Fprintf(&b, "Usage: `trafico %s`\n\n", use)
			}
			if flags := renderFlags(cmd); flags != "" {
				b.WriteString("Flags:\n\n")
				b.WriteString(flags)
				b.WriteString("\n")
			}
		}
		children := cmd.Commands()
		sort.Slice(children, func(i, j int) bool { return children[i].Name() < children[j].Name() })
		for _, child := range children {
			next := "trafico " + child.Name()
			if path != "" {
				next = path + " " + child.Name()
			}
			walk(child, next)
		}
	}
	walk(root, "")

	return b.String()
}

// renderFlags lists the command's own flags, sorted, skipping the generated
// help flag. A flag whose description is empty is still listed: an
// undocumented flag is a defect the spec should show rather than hide.
func renderFlags(cmd *cobra.Command) string {
	flags := cmd.Flags()
	if !flags.HasFlags() {
		return ""
	}
	var lines []string
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Name == "help" {
			return
		}
		def := ""
		if f.DefValue != "" && f.DefValue != "false" {
			def = fmt.Sprintf(" (default `%s`)", f.DefValue)
		}
		line := fmt.Sprintf("- `--%s`%s — %s\n", f.Name, def, f.Usage)
		if f.Shorthand != "" {
			line = fmt.Sprintf("- `-%s`, `--%s`%s — %s\n", f.Shorthand, f.Name, def, f.Usage)
		}
		lines = append(lines, line)
	})
	sort.Strings(lines)
	return strings.Join(lines, "")
}

// writeCLISpec writes the rendered reference to w.
func writeCLISpec(w io.Writer, root *cobra.Command) error {
	_, err := io.WriteString(w, RenderCLISpec(root))
	return err
}
