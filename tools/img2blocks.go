//go:build ignore

// img2blocks turns a PNG into terminal art and writes it as Go source.
//
// The terminal has no pixels, but it has half blocks: one cell is two pixels,
// the top drawn with ▀ in the foreground colour and the bottom with the cell's
// background. With 24-bit colour that is a real picture at a readable size, the
// same trick the ALSA UI uses.
//
// Run it from the repository root:
//
//	go run tools/img2blocks.go -in banner.png -out internal/tui/banner_gen.go \
//	    -const artBanner -cols 76
//
// The output is plain source, so what lands in the repository is reviewable and
// the build needs no image decoder at runtime: the picture is a constant.
//
// This file is excluded from the build by its tag: it is a tool, not a package.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"image"
	"image/png"
	"os"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "", "input PNG")
	out := flag.String("out", "", "output Go file")
	name := flag.String("const", "artBanner", "name of the generated constant")
	cols := flag.Int("cols", 76, "width in terminal cells")
	bgThreshold := flag.Int("bg", 0, "treat pixels darker than this (0-255, every channel) as transparent")
	flag.Parse()
	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "img2blocks: -in and -out are required")
		os.Exit(2)
	}

	file, err := os.Open(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}
	defer func() { _ = file.Close() }()

	source, err := png.Decode(file)
	if err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}

	art := render(source, *cols, *bgThreshold)
	// render never widens the picture past the source, so the width the art
	// really has is the smaller of the two. It has to be emitted: trimming
	// the trailing spaces leaves every row a different length, and a reader
	// cannot tell the picture's width from the art itself.
	artCols := *cols
	if w := source.Bounds().Dx(); w < artCols {
		artCols = w
	}
	var body bytes.Buffer
	fmt.Fprintf(&body, "// Code generated by tools/img2blocks.go from %s. DO NOT EDIT.\n\n", *in)
	fmt.Fprintf(&body, "package tui\n\n")
	fmt.Fprintf(&body, "// %s is the banner as half-block art: one cell is two pixels, the top in\n", *name)
	fmt.Fprintf(&body, "// the foreground colour and the bottom in the cell background. Drawn only\n")
	fmt.Fprintf(&body, "// when the terminal is wide and tall enough to hold it.\n")
	fmt.Fprintf(&body, "//\n")
	fmt.Fprintf(&body, "// One quoted row per line, so the escape sequences stay visible in the\n")
	fmt.Fprintf(&body, "// source: a raw literal would carry the control bytes themselves, which\n")
	fmt.Fprintf(&body, "// no linter accepts and no reviewer can see.\n")
	// One quoted row per line, and the newline that separates rows is part of
	// the literal: the constant concatenates, it does not list.
	quoted := make([]string, len(art))
	for i, line := range art {
		if i < len(art)-1 {
			line += "\n"
		}
		quoted[i] = strconv.Quote(line)
	}
	fmt.Fprintf(&body, "const %s = %s\n", *name, strings.Join(quoted, " +\n\t"))
	fmt.Fprintf(&body, "\n// %sCols is how many cells wide the picture is. Rows have their trailing\n", *name)
	fmt.Fprintf(&body, "// spaces trimmed, so the width cannot be read off the art itself.\n")
	fmt.Fprintf(&body, "const %sCols = %d\n", *name, artCols)

	if err := os.WriteFile(*out, body.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "img2blocks: %s -> %s (%d cols x %d rows)\n", *in, *out, *cols, len(art))
}

// render downscales the image to cols cells wide by averaging each block, then
// emits one string per text row. Averaging rather than sampling matters: a road
// with thin lines sampled at 76 columns loses the lines, averaged it keeps a
// grey band where they were.
func render(source image.Image, cols, bgThreshold int) []string {
	bounds := source.Bounds()
	width, height := bounds.Dx(), bounds.Dy()
	if cols > width {
		cols = width
	}
	scale := float64(width) / float64(cols)

	// Two pixel rows per text row.
	rows := int(float64(height) / scale / 2)
	if rows < 1 {
		rows = 1
	}

	art := make([]string, 0, rows)
	for row := 0; row < rows; row++ {
		var line strings.Builder
		for col := 0; col < cols; col++ {
			top := average(source, bounds, col, row*2, scale)
			bottom := average(source, bounds, col, row*2+1, scale)
			line.WriteString(cell(top, bottom, bgThreshold))
		}
		art = append(art, strings.TrimRight(line.String(), " "))
	}
	return art
}

// average is the mean colour of the block that maps to one half-cell.
func average(source image.Image, bounds image.Rectangle, col, halfRow int, scale float64) rgb {
	x0 := bounds.Min.X + int(float64(col)*scale)
	x1 := bounds.Min.X + int(float64(col+1)*scale)
	// One half-cell covers the same number of pixels vertically as a cell
	// does horizontally: halving here sampled only the top half of the image
	// and stretched it over both rows.
	y0 := bounds.Min.Y + int(float64(halfRow)*scale)
	y1 := bounds.Min.Y + int(float64(halfRow+1)*scale)
	if x1 <= x0 {
		x1 = x0 + 1
	}
	if y1 <= y0 {
		y1 = y0 + 1
	}

	var r, g, b, n uint64
	for y := y0; y < y1; y++ {
		for x := x0; x < x1; x++ {
			pr, pg, pb, pa := source.At(x, y).RGBA()
			if pa == 0 {
				continue
			}
			r += uint64(pr >> 8)
			g += uint64(pg >> 8)
			b += uint64(pb >> 8)
			n++
		}
	}
	if n == 0 {
		return rgb{}
	}
	return rgb{uint8(r / n), uint8(g / n), uint8(b / n)}
}

type rgb struct{ r, g, b uint8 }

// cell renders one terminal cell: the upper half block painted in the top
// pixel's colour over the bottom pixel's colour. A block that is essentially
// black on both halves becomes a space, which keeps the background of the
// terminal showing through instead of painting a black rectangle over it.
func cell(top, bottom rgb, bgThreshold int) string {
	darkTop := int(top.r) <= bgThreshold && int(top.g) <= bgThreshold && int(top.b) <= bgThreshold
	darkBottom := int(bottom.r) <= bgThreshold && int(bottom.g) <= bgThreshold && int(bottom.b) <= bgThreshold
	switch {
	case darkTop && darkBottom:
		return " "
	case darkBottom:
		return fmt.Sprintf("\x1b[38;2;%d;%d;%dm▀\x1b[0m", top.r, top.g, top.b)
	case darkTop:
		return fmt.Sprintf("\x1b[38;2;%d;%d;%dm▄\x1b[0m", bottom.r, bottom.g, bottom.b)
	default:
		return fmt.Sprintf("\x1b[38;2;%d;%d;%dm\x1b[48;2;%d;%d;%dm▀\x1b[0m",
			top.r, top.g, top.b, bottom.r, bottom.g, bottom.b)
	}
}
