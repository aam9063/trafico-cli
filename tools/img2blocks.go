//go:build ignore

// img2blocks turns a PNG into terminal art and writes it as Go source.
//
// The terminal has no pixels, but it has half blocks: one cell is two pixels,
// the top drawn with ▀ in the foreground colour and the bottom with the cell's
// background. With 24-bit colour that is a real picture at a readable size.
//
// Run it from the repository root:
//
//	go run tools/img2blocks.go -in banner.png -out internal/tui/banner_gen.go \
//	    -var artBanners -cols 44,63,73,88,117
//
// One picture is emitted per width, smallest first, so the UI can draw the
// largest one the terminal has room for: detail is bounded by the cells, and
// a wide terminal should not get the picture an 80-column one gets.
//
// The output is plain source, so what lands in the repository is reviewable and
// the build needs no image decoder at runtime: the pictures are constants.
//
// This file is excluded from the build by its tag: it is a tool, not a package.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"image"
	"image/png"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "", "input PNG")
	out := flag.String("out", "", "output Go file")
	name := flag.String("var", "artBanners", "name of the generated slice of pictures")
	colsFlag := flag.String("cols", "76", "comma-separated widths in terminal cells, one picture each")
	colors := flag.Int("colors", 48, "palette size: the source is reduced to this many of its own colours")
	cover := flag.Float64("cover", 0.5, "share of a half-cell one palette colour must cover to be drawn flat")
	cropFlag := flag.String("crop", "", "draw only this area of the source, x0,y0,x1,y1 in pixels (the palette still comes from the whole picture)")
	flag.Parse()
	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "img2blocks: -in and -out are required")
		os.Exit(2)
	}
	widths, err := parseWidths(*colsFlag)
	if err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(2)
	}

	file, err := os.Open(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}
	defer func() { _ = file.Close() }()
	source, err := png.Decode(file)
	if err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}

	pic := load(source)
	pal := newPalette(pic, *colors)
	area := image.Rect(0, 0, pic.w, pic.h)
	if *cropFlag != "" {
		area, err = parseCrop(*cropFlag, area)
		if err != nil {
			fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
			os.Exit(2)
		}
	}

	var body bytes.Buffer
	fmt.Fprintf(&body, "// Code generated by tools/img2blocks.go from %s. DO NOT EDIT.\n\n", *in)
	fmt.Fprintf(&body, "package tui\n\n")
	if *cropFlag != "" {
		fmt.Fprintf(&body, "// %s is drawn from the area %s of the picture, with the\n", *name, *cropFlag)
		fmt.Fprintf(&body, "// palette of the whole picture.\n//\n")
	}
	fmt.Fprintf(&body, "// %s is the banner as half-block art at every width, smallest first:\n", *name)
	fmt.Fprintf(&body, "// one cell is two pixels, the top in the foreground colour and the bottom\n")
	fmt.Fprintf(&body, "// in the cell background. Every row is exactly cols cells wide.\n")
	fmt.Fprintf(&body, "//\n")
	fmt.Fprintf(&body, "// One quoted row per line, so the escape sequences stay visible in the\n")
	fmt.Fprintf(&body, "// source: a raw literal would carry the control bytes themselves, which\n")
	fmt.Fprintf(&body, "// no linter accepts and no reviewer can see.\n")
	fmt.Fprintf(&body, "var %s = []bannerArt{\n", *name)
	for _, cols := range widths {
		if cols > area.Dx() {
			fmt.Fprintf(os.Stderr, "img2blocks: %d columns is wider than the %d-pixel source\n", cols, area.Dx())
			os.Exit(2)
		}
		art := render(pic, pal, area, cols, *cover)
		fmt.Fprintf(&body, "\t{cols: %d, lines: []string{\n", cols)
		for _, line := range art {
			fmt.Fprintf(&body, "\t\t%s,\n", strconv.Quote(line))
		}
		fmt.Fprintf(&body, "\t}},\n")
		fmt.Fprintf(os.Stderr, "img2blocks: %d cols x %d rows\n", cols, len(art))
	}
	fmt.Fprintf(&body, "}\n")

	if err := os.WriteFile(*out, body.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "img2blocks: %v\n", err)
		os.Exit(1)
	}
}

// parseCrop reads -crop: four integers, a non-empty rectangle inside the
// picture.
func parseCrop(s string, bounds image.Rectangle) (image.Rectangle, error) {
	f := strings.Split(s, ",")
	if len(f) != 4 {
		return image.Rectangle{}, fmt.Errorf("-crop wants x0,y0,x1,y1, got %q", s)
	}
	var n [4]int
	for i, v := range f {
		x, err := strconv.Atoi(strings.TrimSpace(v))
		if err != nil {
			return image.Rectangle{}, fmt.Errorf("bad number %q in -crop", v)
		}
		n[i] = x
	}
	r := image.Rect(n[0], n[1], n[2], n[3])
	if r.Empty() || !r.In(bounds) {
		return image.Rectangle{}, fmt.Errorf("-crop %v is empty or outside the %v picture", r, bounds)
	}
	return r, nil
}

// parseWidths reads the -cols list: positive widths, strictly ascending, so
// the generated slice is ordered smallest first without sorting at runtime.
func parseWidths(s string) ([]int, error) {
	var out []int
	for _, f := range strings.Split(s, ",") {
		n, err := strconv.Atoi(strings.TrimSpace(f))
		if err != nil || n < 1 {
			return nil, fmt.Errorf("bad width %q in -cols", f)
		}
		if len(out) > 0 && n <= out[len(out)-1] {
			return nil, fmt.Errorf("-cols must be ascending: %d after %d", n, out[len(out)-1])
		}
		out = append(out, n)
	}
	return out, nil
}

type rgb struct{ r, g, b uint8 }

// vec is a colour as three floats: linear light for averaging, OKLab for
// distances. Averaging in sRGB darkens every edge; measuring distance in
// linear light makes every dark colour look alike, and this picture is a
// night scene where the buildings are only a few steps off the sky.
type vec struct{ x, y, z float64 }

// picture is the decoded source, flattened once.
type picture struct {
	w, h int
	px   []rgb
}

func load(img image.Image) picture {
	b := img.Bounds()
	p := picture{w: b.Dx(), h: b.Dy(), px: make([]rgb, b.Dx()*b.Dy())}
	for y := 0; y < p.h; y++ {
		for x := 0; x < p.w; x++ {
			r, g, bl, _ := img.At(b.Min.X+x, b.Min.Y+y).RGBA()
			p.px[y*p.w+x] = rgb{uint8(r >> 8), uint8(g >> 8), uint8(bl >> 8)}
		}
	}
	return p
}

// palette is the source reduced to a few of its own colours, and every
// source pixel's index into it.
type palette struct {
	colors []rgb
	lab    []vec
	index  []int // per source pixel
}

// newPalette clusters the source's colours with k-means in OKLab, weighted by
// how many pixels carry each one, then replaces every centre with the real
// source colour nearest to it: the art only ever paints colours the picture
// has. Seeding is deterministic (heaviest colour first, then the colour
// farthest from the chosen ones, weighted), so the same PNG always generates
// the same source.
func newPalette(p picture, k int) palette {
	counts := map[rgb]int{}
	for _, c := range p.px {
		counts[c]++
	}
	keys := make([]rgb, 0, len(counts))
	for c := range counts {
		keys = append(keys, c)
	}
	sort.Slice(keys, func(i, j int) bool {
		a, b := keys[i], keys[j]
		if counts[a] != counts[b] {
			return counts[a] > counts[b]
		}
		if a.r != b.r {
			return a.r < b.r
		}
		if a.g != b.g {
			return a.g < b.g
		}
		return a.b < b.b
	})
	if k > len(keys) {
		k = len(keys)
	}
	pts := make([]vec, len(keys))
	weights := make([]float64, len(keys))
	for i, c := range keys {
		pts[i] = oklab(toLinear(c))
		weights[i] = float64(counts[c])
	}

	centres := []vec{pts[0]}
	nearestD := make([]float64, len(pts))
	for i := range pts {
		nearestD[i] = dist(pts[i], pts[0])
	}
	for len(centres) < k {
		best, score := 0, -1.0
		for i := range pts {
			if s := nearestD[i] * math.Sqrt(weights[i]); s > score {
				best, score = i, s
			}
		}
		centres = append(centres, pts[best])
		for i := range pts {
			if d := dist(pts[i], pts[best]); d < nearestD[i] {
				nearestD[i] = d
			}
		}
	}
	for iter := 0; iter < 20; iter++ {
		sum := make([]vec, k)
		w := make([]float64, k)
		for i, pt := range pts {
			c := nearest(centres, pt)
			sum[c].x += pt.x * weights[i]
			sum[c].y += pt.y * weights[i]
			sum[c].z += pt.z * weights[i]
			w[c] += weights[i]
		}
		for c := range centres {
			if w[c] > 0 {
				centres[c] = vec{sum[c].x / w[c], sum[c].y / w[c], sum[c].z / w[c]}
			}
		}
	}

	pal := palette{}
	seen := map[rgb]bool{}
	for _, c := range centres {
		src := keys[nearest(pts, c)]
		if seen[src] {
			continue
		}
		seen[src] = true
		pal.colors = append(pal.colors, src)
		pal.lab = append(pal.lab, oklab(toLinear(src)))
	}
	cache := map[rgb]int{}
	pal.index = make([]int, len(p.px))
	for i, c := range p.px {
		v, ok := cache[c]
		if !ok {
			v = nearest(pal.lab, oklab(toLinear(c)))
			cache[c] = v
		}
		pal.index[i] = v
	}
	return pal
}

// render draws the picture cols cells wide, one string per text row. Each
// half-cell covers a block of source pixels and takes one palette colour:
// the block's dominant colour when it covers at least the cover share --
// flat fills and hard edges stay crisp -- otherwise the palette colour
// nearest the block's true average, so a thin lane line that covers a third
// of a block still shows instead of vanishing under the asphalt.
//
// Only the area of the picture is drawn: the whole of it, or a crop. A crop
// keeps the palette of the whole picture, so a small cut-out paints with
// exactly the colours of the full-size art.
func render(p picture, pal palette, area image.Rectangle, cols int, cover float64) []string {
	scale := float64(area.Dx()) / float64(cols)
	rows := int(math.Round(float64(area.Dy()) / scale / 2))
	if rows < 1 {
		rows = 1
	}
	grid := make([]rgb, cols*rows*2)
	tally := make([]int, len(pal.colors))
	for hy := 0; hy < rows*2; hy++ {
		y0, y1 := span(hy, scale, area.Dy())
		y0, y1 = y0+area.Min.Y, y1+area.Min.Y
		for cx := 0; cx < cols; cx++ {
			x0, x1 := span(cx, scale, area.Dx())
			x0, x1 = x0+area.Min.X, x1+area.Min.X
			for i := range tally {
				tally[i] = 0
			}
			var sum vec
			n := 0
			for y := y0; y < y1; y++ {
				for x := x0; x < x1; x++ {
					l := toLinear(p.px[y*p.w+x])
					sum.x += l.x
					sum.y += l.y
					sum.z += l.z
					tally[pal.index[y*p.w+x]]++
					n++
				}
			}
			top := 0
			for i, t := range tally {
				if t > tally[top] {
					top = i
				}
			}
			c := top
			if float64(tally[top]) < cover*float64(n) {
				mean := vec{sum.x / float64(n), sum.y / float64(n), sum.z / float64(n)}
				c = nearest(pal.lab, oklab(mean))
			}
			grid[hy*cols+cx] = pal.colors[c]
		}
	}

	art := make([]string, rows)
	for row := 0; row < rows; row++ {
		art[row] = emitRow(grid[row*2*cols:(row*2+1)*cols], grid[(row*2+1)*cols:(row*2+2)*cols])
	}
	return art
}

// span is the pixel range [lo, hi) of block i at the given scale, clamped to
// the source and never empty: the last half-row may run past the bottom
// edge when the height does not divide evenly.
func span(i int, scale float64, limit int) (int, int) {
	lo := int(float64(i) * scale)
	hi := int(float64(i+1) * scale)
	if hi > limit {
		hi = limit
	}
	if lo >= hi {
		lo = hi - 1
	}
	return lo, hi
}

// emitRow writes one text row. A colour is sent only when it changes from
// the cell before: the night sky is long runs of one colour, and repeating
// the escape on every cell would triple the size of the source for nothing.
// A cell whose halves match is a space on that background; the row ends with
// a reset so nothing bleeds into the frame after it.
func emitRow(top, bottom []rgb) string {
	var b strings.Builder
	var fg, bg *rgb
	for i := range top {
		t, u := top[i], bottom[i]
		var codes []string
		if t != u && (fg == nil || *fg != t) {
			codes = append(codes, fmt.Sprintf("38;2;%d;%d;%d", t.r, t.g, t.b))
			fg = &top[i]
		}
		if bg == nil || *bg != u {
			codes = append(codes, fmt.Sprintf("48;2;%d;%d;%d", u.r, u.g, u.b))
			bg = &bottom[i]
		}
		if len(codes) > 0 {
			b.WriteString("\x1b[" + strings.Join(codes, ";") + "m")
		}
		if t == u {
			b.WriteByte(' ')
		} else {
			b.WriteString("▀")
		}
	}
	b.WriteString("\x1b[0m")
	return b.String()
}

func nearest(set []vec, c vec) int {
	best, bestD := 0, math.MaxFloat64
	for i, s := range set {
		if d := dist(c, s); d < bestD {
			best, bestD = i, d
		}
	}
	return best
}

func dist(a, b vec) float64 {
	dx, dy, dz := a.x-b.x, a.y-b.y, a.z-b.z
	return dx*dx + dy*dy + dz*dz
}

func toLinear(c rgb) vec {
	return vec{linear(c.r), linear(c.g), linear(c.b)}
}

func linear(c uint8) float64 {
	v := float64(c) / 255
	if v <= 0.04045 {
		return v / 12.92
	}
	return math.Pow((v+0.055)/1.055, 2.4)
}

// oklab maps linear sRGB to OKLab, where equal distances look equally
// different (Björn Ottosson's published matrices).
func oklab(c vec) vec {
	l := math.Cbrt(0.4122214708*c.x + 0.5363325363*c.y + 0.0514459929*c.z)
	m := math.Cbrt(0.2119034982*c.x + 0.6806995451*c.y + 0.1073969566*c.z)
	s := math.Cbrt(0.0883024619*c.x + 0.2817188376*c.y + 0.6299787005*c.z)
	return vec{
		0.2104542553*l + 0.7936177850*m - 0.0040720468*s,
		1.9779984951*l - 2.4285922050*m + 0.4505937099*s,
		0.0259040371*l + 0.7827717662*m - 0.8086757660*s,
	}
}
